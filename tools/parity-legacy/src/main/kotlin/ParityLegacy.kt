import com.github.rodrigotimoteo.mutation.mutator.MutationInfo
import com.github.rodrigotimoteo.mutation.mutator.MutationOperator
import com.github.rodrigotimoteo.mutation.mutator.Mutator
import com.tschuchort.compiletesting.KotlinCompilation
import com.tschuchort.compiletesting.SourceFile
import org.jetbrains.kotlin.compiler.plugin.ExperimentalCompilerApi
import org.jetbrains.kotlin.config.KotlinCompilerVersion
import org.objectweb.asm.util.Printer
import java.io.File
import java.nio.file.Files
import java.security.MessageDigest

private const val LEGACY_CLASS = "com.github.rodrigotimoteo.mutation.mutator.Mutator"

private fun hex(
    algorithm: String,
    bytes: ByteArray,
) = MessageDigest.getInstance(algorithm).digest(bytes).joinToString("") { "%02x".format(it) }

// Mirrors mutkt-testing compileKotlin: file name Source.kt, jvmTarget 17, no inherited classpath.
@OptIn(ExperimentalCompilerApi::class)
private fun compile(source: String): Map<String, ByteArray> {
    val workDir = Files.createTempDirectory("parity-legacy").toFile()
    try {
        val result =
            KotlinCompilation()
                .apply {
                    workingDir = workDir
                    sources = listOf(SourceFile.kotlin("Source.kt", source))
                    jvmTarget = "17"
                    verbose = false
                    inheritClassPath = false
                }.compile()
        check(result.exitCode == KotlinCompilation.ExitCode.OK) { "Kotlin compilation failed: ${result.messages}" }
        val root = result.outputDirectory.toPath()
        return Files.walk(root).use { paths ->
            paths
                .filter { it.toString().endsWith(".class") }
                .toList()
                .associate { root.relativize(it).toString().removeSuffix(".class").replace('/', '.') to Files.readAllBytes(it) }
        }
    } finally {
        workDir.deleteRecursively()
    }
}

private fun row(info: MutationInfo) =
    listOf(
        info.operator.name,
        info.className,
        info.methodName + info.methodDescriptor,
        info.lineNumber.toString(),
        Printer.OPCODES[info.originalOpcode],
    )

/** Args: parity resources directory (fixtures in, legacy-0.3.3.tsv out). */
fun main(args: Array<String>) {
    val dir = File(args.single())
    val fixtures = dir.listFiles { f -> f.name.endsWith(".kt.txt") }!!.sortedBy { it.name }
    val jar = File(Class.forName(LEGACY_CLASS).protectionDomain.codeSource.location.toURI())
    val classes = fixtures.associate { it.name.removeSuffix(".kt.txt") to compile(it.readText()) }

    val rows =
        MutationOperator.entries.flatMap { op ->
            classes.values.flatMap { compiled ->
                compiled.values.flatMap { Mutator(setOf(op)).scanMutations(it).map(::row) }
            }
        }.sortedWith(
            compareBy<List<String>>({ it[0] }, { it[1] }, { it[2] }, { it[3].toInt() }, { it[4] }),
        )

    val header =
        buildList {
            add("# Legacy MutKt 0.3.3 sites: one row per Mutator(setOf(op)).scanMutations hit.")
            add("# Generated by tools/parity-legacy (do not edit); see its README for how to regenerate.")
            add("# legacy mutation-core-0.3.3.jar sha1 ${hex("SHA-1", jar.readBytes())}")
            add("# kotlin ${KotlinCompilerVersion.VERSION} kctfork 0.15.0 jvmTarget 17 file Source.kt")
            classes.forEach { (fixture, compiled) ->
                compiled.toSortedMap().forEach { (name, bytes) -> add("# sha256 $fixture $name ${hex("SHA-256", bytes)}") }
            }
            add("# legacy operator -> new operator id")
            LEGACY_TO_NEW.forEach { (legacy, new) -> add("# map $legacy $new") }
            add("# columns: operator class method+descriptor line opcode")
        }
    File(dir, "legacy-0.3.3.tsv").writeText((header + rows.map { it.joinToString("\t") }).joinToString("\n", postfix = "\n"))
}

private val LEGACY_TO_NEW =
    mapOf(
        "ARITHMETIC" to "arithmetic",
        "CONDITIONALS_BOUNDARY" to "conditionals-boundary",
        "NEGATE_CONDITIONALS" to "negate-conditionals",
        "RETURN_VALS" to "return-vals",
        "NULL_RETURNS" to "null-returns",
        "EMPTY_RETURNS" to "empty-returns",
        "VOID_METHOD_CALLS" to "void-method-calls",
        "NON_VOID_METHOD_CALLS" to "non-void-method-calls",
        "INCREMENTS" to "increments",
        "TRUE_RETURNS" to "true-returns",
        "FALSE_RETURNS" to "false-returns",
        "CONSTRUCTOR_CALLS" to "constructor-calls",
        "DATA_CLASS_COPY" to "data-class-copy",
        "SEALED_WHEN" to "sealed-when",
        "NULL_SAFETY" to "null-safety",
        "COROUTINE" to "coroutine",
    )
